// exportUtils.js — Universal Export & Download Utility for IntelliDoc AI

import { BASE_URL } from "../api/client";

/**
 * Copy text to clipboard and trigger toast
 */
export function copyToClipboard(text, showToast) {
  if (!text) return;
  const cleanText = typeof text === "string" ? text : JSON.stringify(text, null, 2);
  navigator.clipboard.writeText(cleanText);
  showToast?.("Copied to clipboard", "success");
}

/**
 * Download arbitrary string content as a file
 */
export function downloadFile(filename, content, mimeType = "text/plain") {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Export content as PDF via backend or print window fallback
 */
export async function exportPDF(title, content, showToast) {
  const textContent = typeof content === "string" ? content : JSON.stringify(content, null, 2);
  try {
    const res = await fetch(`${BASE_URL}/export/pdf`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ title, content: textContent }),
    });

    if (res.ok) {
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${title.toLowerCase().replace(/\s+/g, "_")}.pdf`;
      a.click();
      URL.revokeObjectURL(url);
      showToast?.("PDF exported successfully", "success");
      return;
    }
  } catch (err) {
    console.warn("Backend PDF export failed, using print fallback:", err);
  }

  // Fallback Print Window as PDF
  printContent(title, textContent);
  showToast?.("Opened print window for PDF export", "info");
}

/**
 * Export content as DOCX via backend or blob download
 */
export async function exportDOCX(title, content, showToast) {
  const textContent = typeof content === "string" ? content : JSON.stringify(content, null, 2);
  try {
    const res = await fetch(`${BASE_URL}/export/docx`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ title, content: textContent }),
    });

    if (res.ok) {
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${title.toLowerCase().replace(/\s+/g, "_")}.docx`;
      a.click();
      URL.revokeObjectURL(url);
      showToast?.("DOCX exported successfully", "success");
      return;
    }
  } catch (err) {
    console.warn("Backend DOCX export failed, downloading text file:", err);
  }

  // Fallback text download with .docx MIME
  downloadFile(`${title.toLowerCase().replace(/\s+/g, "_")}.docx`, textContent, "application/vnd.openxmlformats-officedocument.wordprocessingml.document");
  showToast?.("Downloaded DOCX document", "success");
}

